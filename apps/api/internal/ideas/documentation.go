package ideas

import (
	"net/http"

	documentation "github.com/FacileStudio/Courrier/apps/api/internal/documentation"

	"github.com/FacileStudio/tronc/bulle"
)

// DecisionRequest is the body of an approval answer.
type DecisionRequest struct {
	Approve bool `json:"approve"`
}

var space = documentation.Field{Name: "space_id", Type: "string", Description: "Space to use; omit for personal"}

var paymentRequired = documentation.Error{Status: 402, Code: "payment_required", Description: "The plan has no ai.access."}

// Documentation describes the Ideas routes for the API reference.
var Documentation = documentation.Module{
	Name: "ideas",
	Description: "Proactive AI suggestions generated by Bulle for Courrier, run in place. Courrier calls Bulle as the " +
		"signed-in user through a Registre token exchange. Mounted only when OIDC and BULLE_URL are set. The optional " +
		"space_id must be a space the caller belongs to and that Registre knows. Ideas are paid (ai.access): a plan " +
		"without it gets ai_access false on the list and 402 with an upgrade_url on the other routes.",
	Routes: []documentation.Route{
		{
			Method:       "GET",
			Path:         "/ideas",
			Summary:      "The open ideas of the active space, whether Bulle is generating, and ai_access",
			Auth:         "session cookie or bearer token",
			QueryParams:  []documentation.Field{space},
			ResponseBody: bulle.IdeasPage{},
		},
		{
			Method:       "POST",
			Path:         "/ideas/generate",
			Summary:      "Ask Bulle for a new batch of ideas",
			Description:  "202 when started, 429 past Bulle's daily cap, 409 while a batch runs.",
			Auth:         "session cookie or bearer token",
			QueryParams:  []documentation.Field{space},
			RequestBody:  struct{}{},
			ResponseBody: bulle.Batch{},
			Status:       http.StatusAccepted,
			Errors:       []documentation.Error{paymentRequired},
		},
		{
			Method:       "POST",
			Path:         "/ideas/{id}/run",
			Summary:      "Run an idea as a background Bulle run",
			Auth:         "session cookie or bearer token",
			PathParams:   []documentation.Field{{Name: "id", Type: "string", Description: "Idea id"}},
			QueryParams:  []documentation.Field{space},
			RequestBody:  struct{}{},
			ResponseBody: bulle.RunStart{},
			Status:       http.StatusAccepted,
			Errors:       []documentation.Error{paymentRequired},
		},
		{
			Method:      "POST",
			Path:        "/ideas/{id}/dismiss",
			Summary:     "Hide an idea",
			Auth:        "session cookie or bearer token",
			PathParams:  []documentation.Field{{Name: "id", Type: "string", Description: "Idea id"}},
			RequestBody: struct{}{},
			Status:      http.StatusNoContent,
		},
		{
			Method:       "GET",
			Path:         "/ideas/runs/{run}",
			Summary:      "A run's state, summary, output links and pending approvals",
			Description:  "state is running, needs_approval, done or failed.",
			Auth:         "session cookie or bearer token",
			PathParams:   []documentation.Field{{Name: "run", Type: "string", Description: "Run id"}},
			ResponseBody: bulle.Run{},
		},
		{
			Method:      "POST",
			Path:        "/ideas/runs/{run}/approvals/{call}",
			Summary:     "Approve or decline a call the run is holding",
			Description: "Approving needs ai.access.",
			Auth:        "session cookie or bearer token",
			PathParams: []documentation.Field{
				{Name: "run", Type: "string", Description: "Run id"},
				{Name: "call", Type: "string", Description: "Call id"},
			},
			RequestBody: DecisionRequest{},
			Status:      http.StatusNoContent,
			Errors:      []documentation.Error{paymentRequired},
		},
	},
}
